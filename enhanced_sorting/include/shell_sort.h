#pragma once
#include <vector>
#include <cstddef>

namespace enhanced_sorting {

    // Сортировка Шелла — улучшение сортировки вставками.
    // Идея: сначала сортируем элементы, стоящие далеко друг от друга
    // (с большим шагом), постепенно уменьшая шаг.
    // На последнем шаге (шаг = 1) массив почти отсортирован,
    // и обычная вставка работает за O(n).
    //
    // Сложность зависит от выбора шагов:
    //   - шаги n/2, n/4, ..., 1 — O(n^2) в худшем случае;
    //   - последовательность Кнута (1, 4, 13, 40, ...) — O(n^1.5);
    //   - последовательность Седжвика — O(n^1.3).
    // Мы используем классический вариант n/2, n/4, ..., 1.
    template <typename T>
    void shellSort(std::vector<T>& arr) {
        const std::size_t n = arr.size();
        if (n < 2) return;

        // Начальный шаг = n/2, каждый следующий = половина предыдущего.
        for (std::size_t gap = n / 2; gap > 0; gap /= 2) {

            // Сортировка вставками с шагом gap:
            // сравниваем элементы, стоящие на расстоянии gap друг от друга.
            for (std::size_t i = gap; i < n; ++i) {
                T key = arr[i];
                std::size_t j = i;

                // Сдвигаем элементы, которые больше key, на gap вправо.
                while (j >= gap && arr[j - gap] > key) {
                    arr[j] = arr[j - gap];
                    j -= gap;
                }
                arr[j] = key;
            }
        }
    }

} // namespace enhanced_sorting